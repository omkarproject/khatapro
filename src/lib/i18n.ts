/**
 * Translation helper with smart multi-tier fallback
 */
export function t(key: string, fallback = ''): string {
  if (typeof window === 'undefined') return fallback || key;
  try {
    const lang = localStorage.getItem('khatapro_language') || 'en';
    if (lang === 'en') return fallback || key;

    // 1. Direct language dictionary lookup
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      return TRANSLATIONS[lang][key];
    }

    // 2. Hindi fallback for Indian dialects / languages
    if (TRANSLATIONS['hi'] && TRANSLATIONS['hi'][key]) {
      return TRANSLATIONS['hi'][key];
    }

    return fallback || key;
  } catch {
    return fallback || key;
  }
}
